async function submitAuth(mode){
  const v=id=>{const e=document.getElementById(id);return e?e.value.trim():'';};
  const err=document.getElementById('authErr'),btn=document.getElementById('authBtn');
  const pass=document.getElementById('aPassI').value,su=mode==='signup';
  const body=su?{name:v('aNameI'),farm:v('aFarmI'),email:v('aEmailI'),password:pass,lang:S.lang}:{email:v('aEmailI'),password:pass};
  err.style.display='none';
  if(!body.email||!pass||(su&&!body.name)){err.textContent=t('aErrFill');err.style.display='block';return;}
  btn.disabled=true;
  try{
    USER=(await api('/auth/'+mode,{method:'POST',body:JSON.stringify(body)})).user;
    S=await api('/state');if(!LANGS.includes(S.lang))S.lang='en';ONLINE=true;save();
    enterApp();toast(t(su?'tWelcome':'tBack',{n:USER.name.split(' ')[0]}));
  }catch(e){
    err.textContent=e.status?e.message:t('tSyncFail');err.style.display='block';btn.disabled=false;
  }
}

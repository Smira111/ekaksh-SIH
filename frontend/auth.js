async function api(path,opts){
  const res=await fetch(API+path,{credentials:'same-origin',headers:{'Content-Type':'application/json'},...opts});
  let j=null;try{j=await res.json();}catch(e){}
  if(!res.ok){
    const e=new Error((j&&j.error)||'API error '+res.status);e.status=res.status;
    if(res.status===401&&USER&&!path.startsWith('/auth/')){USER=null;showPublic('login');}
    throw e;
  }
  return j;
}
async function init(){
  try{
    USER=(await api('/auth/me')).user;S=await api('/state');ONLINE=true;
    if(!LANGS.includes(S.lang))S.lang='en';save();enterApp();
  }catch(e){
    if(e.status===401){ONLINE=true;showPublic('landing');}
    else{ONLINE=false;USER=null;enterApp();toast(t('tOffline'));}   // no backend: keep the old standalone demo
  }
}
